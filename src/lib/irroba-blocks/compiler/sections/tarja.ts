import { generateBenefitsBannerDataUri } from "../../banner-art-generator";
import { getBenefitSvgIcon } from "../../icons";
import { escapeAttr, escapeHtml, sanitizeCssColor, sanitizeUrl } from "../../sanitize";
import { CONTAINER_WIDTH_PX, PALETTE, TARJA_WIDTH, STOREFRONT_GRAYS as G } from "@/lib/layout-patterns";
import type { StoreBlueprint } from "@/lib/types/blueprint";
import { RADIUS_MAP } from "../helpers";

export function renderTarjaBenefitsHtml(bp: StoreBlueprint): string {
  const cfg = bp.sections.benefitsBanner;
  const bg = sanitizeCssColor(cfg?.backgroundColor ?? bp.theme.neutralBackground, PALETTE.neutralSurface);
  const primary = sanitizeCssColor(bp.theme.primaryBackground, PALETTE.ink);
  const primaryFg = sanitizeCssColor(bp.theme.primaryForeground, PALETTE.white);
  const bodyColor = sanitizeCssColor(bp.theme.bodyForeground, PALETTE.ink);
  const radius = RADIUS_MAP[bp.theme.radius].css;

  const maxHeightPx = Math.min(260, Math.max(36, cfg?.maxHeightPx ?? 120));
  const maxWidthCss = cfg?.fullWidth
    ? "100%"
    : `${Math.min(TARJA_WIDTH.max, Math.max(TARJA_WIDTH.min, cfg?.maxWidthPx ?? CONTAINER_WIDTH_PX))}px`;
  const paddingY = Math.min(48, Math.max(0, cfg?.paddingY ?? 14));

  // 1) Custom single image banner (uploaded/pasted or generated by AI)
  if (cfg?.mode === "custom-image" && cfg.customImageUrl) {
    const imgUrl = escapeAttr(sanitizeUrl(cfg.customImageUrl, ""));
    return `<div style="position:relative;left:50%;width:100vw;max-width:100vw;margin-left:-50vw;background:${bg};padding:${paddingY}px 16px;box-sizing:border-box;">
  <div style="max-width:${maxWidthCss};margin:0 auto;display:flex;justify-content:center;align-items:center;">
    <img src="${imgUrl}" alt="Benefícios ${escapeAttr(bp.brand.name)}" referrerpolicy="no-referrer" style="max-height:${maxHeightPx}px;width:auto;max-width:100%;height:auto;object-fit:contain;display:block;border-radius:${radius};" />
  </div>
</div>`;
  }

  // 2) Original artwork images extracted directly from the client store
  if (cfg?.mode === "site-images" && cfg.siteImageUrls.length > 0) {
    const imgsHtml = cfg.siteImageUrls
      .slice(0, 6)
      .map(
        (rawUrl, idx) =>
          `<div style="flex:1 1 120px;max-width:195px;display:flex;align-items:center;justify-content:center;">
  <img src="${escapeAttr(sanitizeUrl(rawUrl, ""))}" alt="Benefício ${idx + 1}" referrerpolicy="no-referrer" style="max-height:${maxHeightPx}px;width:auto;max-width:100%;height:auto;object-fit:contain;display:block;" />
</div>`
      )
      .join("\n      ");

    return `<div style="position:relative;left:50%;width:100vw;max-width:100vw;margin-left:-50vw;background:${bg};padding:${paddingY}px 16px;box-sizing:border-box;">
  <div style="max-width:${maxWidthCss};margin:0 auto;display:flex;flex-wrap:wrap;gap:12px;align-items:center;justify-content:center;">
      ${imgsHtml}
  </div>
</div>`;
  }

  // 3) Generated graphic SVG banner artwork (clean, zero top/bottom lines)
  if (cfg?.mode !== "cards") {
    const dataUri = generateBenefitsBannerDataUri(bp);
    return `<div style="position:relative;left:50%;width:100vw;max-width:100vw;margin-left:-50vw;background:${bg};padding:${paddingY}px 16px;box-sizing:border-box;">
  <div style="max-width:${maxWidthCss};margin:0 auto;display:flex;justify-content:center;align-items:center;">
    <img src="${escapeAttr(dataUri)}" alt="Vantagens ${escapeAttr(bp.brand.name)}" style="max-height:${maxHeightPx}px;width:auto;max-width:100%;height:auto;object-fit:contain;display:block;border-radius:${radius};" />
  </div>
</div>`;
  }

  // 4) Editable cards fallback with Material SVG icons (no emojis)
  const itemsHtml = bp.sections.benefits
    .slice(0, 4)
    .map((b) => {
      return `<div style="flex:1 1 220px;min-width:200px;display:flex;align-items:center;gap:14px;padding:14px 18px;background:#ffffff;border-radius:${radius};border:1px solid rgba(0,0,0,0.06);box-sizing:border-box;">
  <div style="width:42px;height:42px;flex-shrink:0;border-radius:${radius};background:${primary};color:${primaryFg};display:flex;align-items:center;justify-content:center;">${getBenefitSvgIcon(b.icon)}</div>
  <div>
    <div style="font-size:14px;font-weight:700;color:${bodyColor};margin-bottom:2px;">${escapeHtml(b.title)}</div>
    <div style="font-size:12px;color:${G.gray600};line-height:1.35;">${escapeHtml(b.subtitle)}</div>
  </div>
</div>`;
    })
    .join("\n      ");

  return `<div style="position:relative;left:50%;width:100vw;max-width:100vw;margin-left:-50vw;background:${bg};padding:${paddingY}px 20px;box-sizing:border-box;">
  <div style="max-width:${maxWidthCss};margin:0 auto;display:flex;flex-wrap:wrap;gap:14px;justify-content:space-between;">
      ${itemsHtml}
  </div>
</div>`;
}
